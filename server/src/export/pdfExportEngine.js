/**
 * Main Entry Point: Generates complete multi-page PDF Credit Appraisal Memorandum as a Buffer
 * 
 * @param {Object} params
 * @param {Object} params.dpr - Complete output from dprEngine.generateDprProjections()
 * @param {Object} params.normalizedData - Normalized input convergence data
 * @returns {Promise<Buffer>} - Buffer of the generated .pdf document
 */
export async function generateDprPdfDocument({ dpr, normalizedData }) {
  if (!dpr || !dpr.metadata || !Array.isArray(dpr.projectedPnl)) {
    throw new Error('Invalid DPR data object provided to PDF appraisal engine.');
  }

  const data = normalizedData || {};
  const entityName = dpr.metadata.entityName || 'MSME Borrower';

  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: 'A4',
        margin: 36,
        bufferPages: true,
        compress: false,
        info: {
          Title: `Credit Appraisal Memorandum - ${entityName}`,
          Author: 'MSME CreditOS Bank DPR Engine',
          Subject: 'Commercial Credit Assessment & Financial Projections',
          Keywords: 'DPR, CMA, Credit Appraisal, MSME, Banking, DSCR'
        }
      });

      const chunks = [];
      doc.on('data', chunk => chunks.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', err => reject(err));

      // Build 7 Structured Pages
      // Page 1: Executive Summary
      buildPage1(doc, dpr, data);

      // Page 2: Project Cost & Means of Finance
      doc.addPage();
      buildPage2(doc, dpr, data);

      // Page 3: 5-Year Projected P&L
      doc.addPage();
      buildPage3(doc, dpr, data);

      // Page 4: 5-Year Projected Balance Sheet
      doc.addPage();
      buildPage4(doc, dpr);

      // Page 5: Working Capital Assessment
      doc.addPage();
      buildPage5(doc, dpr);

      // Page 6: Term Loan Amortization & DSCR
      doc.addPage();
      buildPage6(doc, dpr);

      // Page 7: Regulatory Compliance & Sign-Off
      doc.addPage();
      buildPage7(doc, dpr);

      // Global Header/Footer Pass across all buffered pages
      const range = doc.bufferedPageRange();
      const totalPages = range.count;

      for (let i = 0; i < totalPages; i++) {
        doc.switchToPage(i);
        drawPageHeaderFooter(doc, i + 1, totalPages, entityName);
      }

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}
